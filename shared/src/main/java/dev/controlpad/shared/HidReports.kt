package dev.controlpad.shared

import kotlin.math.*

/** 标准 HID 报告：鼠标 1、Consumer Control 2、键盘 3；蓝牙与 UHID 共用。 */
object HidReports {
    val descriptor:ByteArray=createDescriptor()
    private fun createDescriptor()=intArrayOf(
        0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x01,0x09,0x01,0xA1,0x00,
        0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,
        0x95,0x01,0x75,0x05,0x81,0x03,0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,
        0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x03,0x81,0x06,0xC0,0xC0,
        0x05,0x0C,0x09,0x01,0xA1,0x01,0x85,0x02,0x15,0x00,0x26,0xFF,0x03,
        0x19,0x00,0x2A,0xFF,0x03,0x75,0x10,0x95,0x01,0x81,0x00,0xC0,
        0x05,0x01,0x09,0x06,0xA1,0x01,0x85,0x03,0x05,0x07,0x19,0xE0,0x29,0xE7,
        0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x08,0x81,0x02,0x75,0x08,0x95,0x01,0x81,0x03,
        0x19,0x00,0x29,0x65,0x15,0x00,0x25,0x65,0x75,0x08,0x95,0x06,0x81,0x00,0xC0
    ).map { it.toByte() }.toByteArray()
    fun mouse(buttons:Int,x:Int=0,y:Int=0,wheel:Int=0)=byteArrayOf((buttons and 7).toByte(),x.coerceIn(-127,127).toByte(),y.coerceIn(-127,127).toByte(),wheel.coerceIn(-127,127).toByte())
    fun consumer(usage:Int)=byteArrayOf(usage.toByte(),(usage ushr 8).toByte())
    fun keyboard(usages:Collection<Int>)=ByteArray(8).apply { usages.take(6).forEachIndexed { i,key->this[i+2]=key.toByte() } }
    // 安卓 KeyEvent 常量，保持此文件可在普通 JVM 中验证。
    fun consumerUsage(code:Int)=when(code) { 3->0x223; 4->0x224; 85->0xCD; 24->0xE9; 25->0xEA; else->0 }
    fun keyboardUsage(code:Int)=when(code) { 19->0x52; 20->0x51; 21->0x50; 22->0x4F; 23->0x28; else->0 }
}

/** 保留小数位移和滚动，不让慢速移动丢失；大位移拆成有符号 8 位报告。 */
class HidMouse(private val send:(ByteArray)->Unit) {
    private var buttons=0; private var x=0f; private var y=0f; private var wheel=0f
    fun move(dx:Float,dy:Float) { x+=dx.coerceIn(-2048f,2048f); y+=dy.coerceIn(-2048f,2048f); flush() }
    fun scroll(dy:Float) { wheel+=(dy/48f).coerceIn(-64f,64f); flush() }
    private fun flush() {
        while(abs(x)>=1 || abs(y)>=1 || abs(wheel)>=1) {
            val dx=x.toInt().coerceIn(-127,127); val dy=y.toInt().coerceIn(-127,127); val dw=wheel.toInt().coerceIn(-127,127)
            send(HidReports.mouse(buttons,dx,dy,dw)); x-=dx; y-=dy; wheel-=dw
        }
    }
    fun down() { buttons=1; send(HidReports.mouse(buttons)) }
    fun up() { buttons=0; send(HidReports.mouse(0)) }
    fun click() { down(); up() }
    fun cancel() { up(); x=0f; y=0f; wheel=0f }
}
